/* ============================================================================
   Composer lifespans + era labels, extracted from the sourced biographies.

   Nothing here is invented: every birth/death year and every era phrase is read
   back out of worker/composer-bios.js, which was itself written from Wikipedia
   with the citation kept in the text. A piece whose own composition year cannot
   be sourced can then still say something true and checkable —
   "written during Chopin's lifetime (1810–1849), the Romantic era" — instead of
   showing a guessed year.

   Run:  node tools/build-composer-dates.mjs
   ========================================================================== */
import fs from 'fs';
const ROOT = '/Users/nurettinkahraman/Documents/PYTHON/4_DOREDOG';

const raw = fs.readFileSync(ROOT + '/worker/composer-bios.js', 'utf8');
const BIOS = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));

const plain = (h) => h.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

/* The bios open with a parenthetical: "(born 31 March 1685 in Eisenach; died 28 July 1750 in Leipzig)"
   with variants — "baptised September 1653", "born Isaac Manuel …; 29 May 1860 in Camprodon", "aged 24". */
function lifespan(text) {
  // Walk every top-level parenthetical: the name itself can carry one
  // ("Christoph Willibald (Ritter von) Gluck") before the dates arrive.
  for (let i = 0; i < text.length; i++) {
    if (text[i] !== '(') continue;
    let depth = 0, close = -1;
    for (let j = i; j < text.length; j++) {
      if (text[j] === '(') depth++;
      else if (text[j] === ')') { depth--; if (!depth) { close = j; break; } }
    }
    if (close < 0) break;
    const inner = text.slice(i + 1, close);
    i = close;
    // "died 28 July 1750", "d. 1750", or a dash span "1 March 1839 … – 10 February 1927"
    const cut = inner.search(/\bdied\b|\bd\.\s|[–—]/i);
    if (cut < 0) continue;
    const born = inner.slice(0, cut).match(/\b(1[0-9]{3}|20[0-9]{2})\b/);
    const died = inner.slice(cut).match(/\b(1[0-9]{3}|20[0-9]{2})\b/);
    if (!born || !died) continue;
    const b = +born[1], d = +died[1];
    if (d < b || d - b > 110) continue;
    return [b, d];
  }
  return null;
}

/* The era is the biography's own wording — "a German composer of the late Baroque period",
   "a German‑born Baroque composer", "a French Romantic composer". If the biography does not
   name a period, we say nothing about one: a lifespan and a century are facts, an era we
   picked ourselves would be a guess. */
const STYLE = '(?:Baroque|Classical|Romantic|Renaissance|Impressionist|Ragtime|Rococo|Galant|Medieval)';
const ERA_RES = [
  new RegExp('\\bof the ((?:[a-z‐-―\\- ]{0,18})?' + STYLE + '(?:[a-z‐-―\\- ]{0,18})?)\\s*(?:period|era)\\b', 'i'),
  new RegExp('\\b(?:an?|the)\\s+(?:[A-Za-zÀ-ÿ‐-―\\-]+\\s+){0,3}?((?:late|early|mid|high)?[‐-―\\- ]?' + STYLE + ')\\s+composer\\b', 'i')
];

const ORD = (c) => c + (c % 10 === 1 && c !== 11 ? 'st' : c % 10 === 2 && c !== 12 ? 'nd' : c % 10 === 3 && c !== 13 ? 'rd' : 'th');

const out = {};
const failed = [];
for (const [name, html] of Object.entries(BIOS)) {
  const text = plain(html);
  const span = lifespan(text);
  if (!span) { failed.push(name); continue; }
  const [b, d] = span;
  const mid = Math.round((b + d) / 2);
  let era = '';
  for (const re of ERA_RES) {
    const m = text.match(re);
    if (m) { era = m[1].trim().replace(/\s+/g, ' ').replace(/[‐-―]/g, '-'); break; }
  }
  if (era.length > 34) era = '';
  const rec = { b: b, d: d, century: ORD(Math.floor(mid / 100) + 1) + ' century' };
  if (era) rec.era = era;                 // present only when the biography says so
  out[name] = rec;
}

const banner = `/* Generated by tools/build-composer-dates.mjs — do not hand-edit.
   Lifespans and era wording read back out of the sourced composer biographies. */`;
fs.writeFileSync(ROOT + '/worker/composer-dates.js',
  banner + '\nexport const DATES = ' + JSON.stringify(out) + ';\n');
fs.writeFileSync(ROOT + '/js/composer-dates.js',
  banner + '\nwindow.DRD = window.DRD || {};\nDRD.COMPOSER_DATES = ' + JSON.stringify(out) + ';\n');

console.log('composers with dates: ' + Object.keys(out).length + ' / ' + Object.keys(BIOS).length);
console.log("era named by the bio: " + Object.values(out).filter((x) => x.era).length);
if (failed.length) console.log('no lifespan found: ' + failed.join(', '));
