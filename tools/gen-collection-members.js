/* ============================================================================
   Freeze collection membership for the edge Worker.

   The collections are defined once, in js/site.js, as match() predicates over the
   catalogue. Rather than reimplement those rules in the Worker (two copies that
   would drift), we run the real ones here and emit the resulting id lists.

   Run:  node tools/gen-collection-members.js     (after any catalogue change)
   ========================================================================== */
const fs = require('fs');
// Derive the repo root from this file's own location — see the note in the .mjs tools:
// an absolute path meant a tool run from a worktree wrote to the main checkout instead.
const ROOT = require('path').resolve(__dirname, '..');

// site.js expects a browser: give it just enough of one to define DRD.COLLECTIONS
global.window = { addEventListener() {}, matchMedia: () => ({ matches: false, addEventListener() {} }), location: { pathname: '/', search: '' } };
global.document = {
  documentElement: { getAttribute: () => '2026', style: { setProperty() {} }, classList: { add() {}, remove() {}, toggle() {} } },
  addEventListener() {}, getElementById: () => null, querySelector: () => null, querySelectorAll: () => [],
  createElement: () => ({ style: {}, classList: { add() {} }, appendChild() {}, setAttribute() {} }), body: { appendChild() {} }
};
global.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
global.navigator = { userAgent: 'node' };

require(ROOT + '/js/data.js');
require(ROOT + '/js/site.js');
// site.js is browser code: inside it `DRD` resolves through window. Node has no such
// binding, so publish it as a real global before calling anything site.js defined.
global.DRD = window.DRD;

const SONGS = window.DRD.SONGS;
const COLLECTIONS = window.DRD.COLLECTIONS;
if (!COLLECTIONS) throw new Error('DRD.COLLECTIONS not defined — did js/site.js change?');

// Use the site's own collectionSongs(), not a re-implementation: it applies the match
// rules AND the ordering (First Steps sorts gentlest-first), so the server-rendered list
// reads in the same order as the grid a visitor sees.
const out = {};
for (const c of COLLECTIONS) {
  let list;
  try { list = window.DRD.collectionSongs(c.slug); }
  catch (e) { list = SONGS.filter((s) => { try { return c.match(s); } catch (_) { return false; } }); }
  out[c.slug] = list.map((s) => s.id);
}

// The Worker used to keep its own hand-typed copy of every collection's title and
// blurb under a "keep in sync with js/site.js" comment, which is the kind of comment
// that stops being true. Emit them from the real definitions instead.
const meta = {};
for (const c of COLLECTIONS) meta[c.slug] = [c.title, c.sub];

fs.writeFileSync(ROOT + '/worker/collection-members.js',
  '// AUTO-GENERATED by tools/gen-collection-members.js — do not hand-edit.\n' +
  '// slug -> the ids that the match() rules in js/site.js select.\n' +
  'export const MEMBERS = ' + JSON.stringify(out) + ';\n' +
  '// slug -> [title, blurb], straight from DRD.COLLECTIONS.\n' +
  'export const COLLECTIONS = ' + JSON.stringify(meta) + ';\n');

console.log('collections: ' + Object.keys(out).length);
for (const [slug, ids] of Object.entries(out)) console.log('  ' + slug.padEnd(24) + ids.length);
