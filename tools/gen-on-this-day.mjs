/* ============================================================================
   "On This Day in Music" — built ONLY from already source-verified material.

   Sources (no new claims are invented here):
     • worker/composer-bios.js   — birth/death dates, each cited to Wikipedia
     • marketing/content-drafts/song-notes.md — dated facts in the song notes

   Emits js/on-this-day.js:  DRD.ONTHISDAY["MM-DD"] = [{ y, t, c?, s? }]
     y = year, t = text, c = composer name (links to /composer), s = song id.

   Run:  node tools/gen-on-this-day.mjs
   ========================================================================== */
import fs from 'fs';
const ROOT = '/Users/nurettinkahraman/Documents/PYTHON/4_DOREDOG';

const MON = { january: 1, february: 2, march: 3, april: 4, may: 5, june: 6, july: 7,
              august: 8, september: 9, october: 10, november: 11, december: 12 };
const key = (d, mName) => String(MON[mName.toLowerCase()]).padStart(2, '0') + '-' + String(d).padStart(2, '0');

const EVENTS = {};
function add(k, ev) { (EVENTS[k] = EVENTS[k] || []).push(ev); }

// ---- 1) composer births & deaths -------------------------------------------
const biosSrc = fs.readFileSync(ROOT + '/worker/composer-bios.js', 'utf8');
const BIOS = (await import('file://' + ROOT + '/worker/composer-bios.js')).BIOS;

let births = 0, deaths = 0;
for (const [name, html] of Object.entries(BIOS)) {
  const txt = html.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ');
  // "(born 31 March 1685 in Eisenach, Germany; died 28 July 1750 in Leipzig)"
  const b = txt.match(/born[^;)]*?\b(\d{1,2})\s+([A-Z][a-z]+)\s+(\d{4})/);
  const d = txt.match(/died\s+(\d{1,2})\s+([A-Z][a-z]+)\s+(\d{4})/);
  const short = name.replace(/\s*\([^)]*\)/, '').trim();

  if (b && MON[b[2].toLowerCase()]) {
    add(key(b[1], b[2]), { y: +b[3], t: short + ' was born.', c: name });
    births++;
  }
  if (d && MON[d[2].toLowerCase()]) {
    add(key(d[1], d[2]), { y: +d[3], t: short + ' died.', c: name });
    deaths++;
  }
}

// ---- 2) dated facts already written into the verified song notes ------------
// Only exact day-month-year statements are used; each already carries a source
// link on the song page itself.
const DATED = [
  ['27', 'April', 1810, 'Beethoven dated the manuscript of Für Elise.', 'fur-elise'],
  ['29', 'December', 1902, '“The Entertainer” was copyrighted by Scott Joplin.', 'the-entertainer'],
  ['18', 'September', 1899, 'Scott Joplin’s “Maple Leaf Rag” was copyrighted.', 'maple-leaf-rag'],
  ['15', 'February', 1867, '“The Blue Danube” was first performed in Vienna.', 'blue-danube'],
  ['4', 'March', 1877, 'Tchaikovsky’s Swan Lake premiered at the Bolshoi Theatre.', 'swan-lake'],
  ['3', 'March', 1875, 'Bizet’s Carmen premiered at the Opéra-Comique in Paris.', 'carmen-habanera'],
  ['10', 'August', 1787, 'Mozart completed Eine kleine Nachtmusik in Vienna.', 'eine-kleine-nachtmusik'],
  ['2', 'June', 1847, 'Mendelssohn’s Wedding March had its earliest documented use at a wedding.', 'wedding-march'],
  ['18', 'December', 1892, 'Tchaikovsky’s The Nutcracker premiered.', 'sugar-plum-fairy'],
  ['3', 'November', 1900, 'Rimsky-Korsakov’s The Tale of Tsar Saltan — source of Flight of the Bumblebee — premiered in Moscow.', 'flight-of-the-bumblebee'],
  ['2', 'April', 1888, 'Satie completed the three Gymnopédies.', 'gymnopedie-no-1'],
  ['25', 'November', 1888, 'Fauré’s Pavane was first performed in its orchestral form.', 'pavane-faure'],
  ['24', 'December', 1818, 'Franz Gruber composed the music to “Silent Night”.', 'silent-night'],
];
let songEvents = 0;
for (const [d, m, y, t, s] of DATED) {
  if (!MON[m.toLowerCase()]) continue;
  add(key(d, m), { y, t, s });
  songEvents++;
}

// ---- 3) sort each day chronologically & write -------------------------------
for (const k of Object.keys(EVENTS)) EVENTS[k].sort((a, b) => a.y - b.y);

const days = Object.keys(EVENTS).sort();
const total = days.reduce((n, k) => n + EVENTS[k].length, 0);

fs.writeFileSync(ROOT + '/js/on-this-day.js',
  '/* AUTO-GENERATED by tools/gen-on-this-day.mjs — do not hand-edit.\n' +
  '   Every entry derives from already source-verified data (composer bios / song notes). */\n' +
  'window.DRD=window.DRD||{};DRD.ONTHISDAY=' + JSON.stringify(EVENTS) + ';\n');

console.log('composer births: ' + births + ' | deaths: ' + deaths + ' | dated song events: ' + songEvents);
console.log('wrote js/on-this-day.js — ' + total + ' events across ' + days.length + '/366 days (' +
  Math.round(100 * days.length / 366) + '% coverage)');
