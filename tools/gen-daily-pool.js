/* ============================================================================
   The pool the daily melody is drawn from.

   A daily puzzle only works if the answer is guessable, so the pool is the
   recognisable end of the catalogue: anything with an editorial note, cover art,
   or the featured flag. The order is shuffled once here with a fixed seed and
   then frozen, so the sequence is stable for everybody and does not shift when
   the catalogue grows — a piece that was #12 stays #12.

   Run:  node tools/gen-daily-pool.js
   ========================================================================== */
const fs = require('fs');
// Derive the repo root from this file's own location — see the note in the .mjs tools:
// an absolute path meant a tool run from a worktree wrote to the main checkout instead.
const ROOT = require('path').resolve(__dirname, '..');

global.window = {};
require(ROOT + '/js/data.js');
const SONGS = window.DRD.SONGS;

const notesSrc = fs.readFileSync(ROOT + '/worker/song-notes.js', 'utf8');
const NOTES = JSON.parse(notesSrc.split('export const NOTES = ')[1].replace(/;\s*$/, ''));

const eligible = SONGS.filter((s) =>
  (NOTES[s.id] || (s.cover && s.cover.image) || s.featured) &&
  s.dur >= 20 && s.dur <= 900);

// deterministic shuffle (mulberry32) — a fixed seed keeps the order reproducible
let seed = 0x5f3d7c11;
const rnd = () => {
  seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
/* APPEND-ONLY. The header above has always promised that a piece which was #12
   stays #12, but the original implementation reshuffled the whole eligible set on
   every run — so adding a single song note (which is what makes a piece eligible)
   silently rewrote the entire calendar. The pool had drifted from 92 entries to
   139 and day 1 had changed from the Minute Waltz to a Chopin nocturne.

   So: keep the existing order for everything still eligible, shuffle only what is
   new, and append it. Growing the pool now extends the calendar instead of
   replacing it. */
const eligibleIds = new Set(eligible.map((s) => s.id));
const live = new Set(SONGS.map((s) => s.id));

let existing = [];
try {
  const prev = fs.readFileSync(ROOT + '/js/daily-pool.js', 'utf8');
  existing = JSON.parse(prev.match(/DRD\.DAILY_POOL = (\[[\s\S]*?\]);/)[1]);
} catch (e) { /* first run */ }

// A piece that left the catalogue has to go, and that does shift the days after it —
// unavoidable, so say so loudly rather than let the calendar move quietly.
const dropped = existing.filter((id) => !live.has(id));
if (dropped.length) console.log('WARNING: dropping ' + dropped.length + ' piece(s) no longer in the catalogue — days after them shift: ' + dropped.join(', '));

const kept = existing.filter((id) => live.has(id));
const keptSet = new Set(kept);
const fresh = eligible.filter((s) => !keptSet.has(s.id));

for (let i = fresh.length - 1; i > 0; i--) {
  const j = Math.floor(rnd() * (i + 1));
  const t = fresh[i]; fresh[i] = fresh[j]; fresh[j] = t;
}

const ids = kept.concat(fresh.map((s) => s.id));
fs.writeFileSync(ROOT + '/js/daily-pool.js',
  '/* Generated by tools/gen-daily-pool.js — do not hand-edit, and do not reorder:\n' +
  '   the sequence is what makes every visitor get the same melody on the same day. */\n' +
  'window.DRD = window.DRD || {};\n' +
  'DRD.DAILY_POOL = ' + JSON.stringify(ids) + ';\n');

console.log('daily pool: ' + ids.length + ' pieces (' + Math.round(ids.length / 30.4) + ' months before it repeats)');
console.log('  kept in place: ' + kept.length + ' | appended: ' + fresh.length + ' | dropped: ' + dropped.length);
console.log('first ten: ' + ids.slice(0, 10).map((id) => window.DRD.getSong(id).title).join(' · '));
