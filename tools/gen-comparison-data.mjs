/* ============================================================================
   Measure the numbers the comparison pages are built on.

   Same instrument as tools/gen-article-lists.mjs — the site's own parseNotation
   and buildTimeline, not a second hand-rolled note parser — so a figure quoted
   on a comparison page and a figure quoted in a measured guide always agree.

   Writes js/comparison-data.js (read by the pages) and prints a summary.
   Run: node tools/gen-comparison-data.mjs
   ========================================================================== */
import fs from 'fs';
import { createRequire } from 'module';

const ROOT = decodeURIComponent(new URL('..', import.meta.url).pathname).replace(/\/$/, '');
const require2 = createRequire(import.meta.url);

global.window = {};
Object.defineProperty(global, 'navigator', { value: { userAgent: 'node' }, configurable: true });
require2(ROOT + '/js/data.js');
require2(ROOT + '/js/player.js');
const DRD = global.window.DRD;
const SONGS = DRD.SONGS;

function notationOf(id) {
  const f = ROOT + '/songs/' + id + '.js';
  if (!fs.existsSync(f)) return null;
  const m = fs.readFileSync(f, 'utf8').match(/=\s*(["'`])([\s\S]*)\1\s*;?\s*$/);
  if (!m) return null;
  return m[2].replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\'/g, "'").replace(/\\\\/g, '\\');
}

const measured = [];
for (const s of SONGS) {
  const nota = notationOf(s.id);
  if (!nota) continue;
  let cols;
  try { cols = DRD.buildTimeline(DRD.parseNotation(nota)).cols; } catch (e) { continue; }
  let lo = Infinity, hi = -Infinity, notes = 0, sharps = 0, chords = 0;
  for (const col of cols) {
    if (col.events.length > 1) chords++;
    for (const ev of col.events) {
      notes++;
      if (ev.midi < lo) lo = ev.midi;
      if (ev.midi > hi) hi = ev.midi;
      if (/[A-G]/.test(ev.letter)) sharps++;
    }
  }
  if (!notes) continue;
  measured.push({
    id: s.id, title: s.title, composer: s.composer, genre: s.genre, ds: s.ds,
    dur: s.dur || 0, notes, sharps, chords,
    span: hi - lo + 1,                                   // inclusive key count
    nps: s.dur ? notes / s.dur : 0,
  });
}

const median = (a) => { const b = a.slice().sort((x, y) => x - y); return b.length ? b[Math.floor(b.length / 2)] : 0; };

// --- keyboard tiers: a piece fits if its whole span does -------------------
const KEYS = [25, 37, 49, 61, 76, 88];
const fits = {};
for (const k of KEYS) fits[k] = measured.filter((m) => m.span <= k).length;

// --- per composer ---------------------------------------------------------
const byComposer = {};
for (const m of measured) (byComposer[m.composer] = byComposer[m.composer] || []).push(m);
const composerStats = {};
for (const [c, list] of Object.entries(byComposer)) {
  composerStats[c] = {
    n: list.length,
    median: median(list.map((m) => m.ds)),
    easiest: list.slice().sort((a, b) => a.ds - b.ds)[0],
    under30: list.filter((m) => m.ds < 30).length,
    under45: list.filter((m) => m.ds < 45).length,
    noSharps: list.filter((m) => m.sharps === 0).length,
  };
}

// --- per era --------------------------------------------------------------
const byEra = {};
for (const m of measured) (byEra[m.genre] = byEra[m.genre] || []).push(m);
const eraStats = {};
for (const [g, list] of Object.entries(byEra)) {
  eraStats[g] = {
    n: list.length,
    median: median(list.map((m) => m.ds)),
    under30: list.filter((m) => m.ds < 30).length,
    medianSpan: median(list.map((m) => m.span)),
    chordRate: Math.round((list.filter((m) => m.chords > m.notes * 0.15).length / list.length) * 100),
  };
}

// --- named head-to-head pieces the comparison pages cite -------------------
const PICK = ['fur-elise', 'moonlight-sonata', 'gymnopedie-no-1', 'clair-de-lune',
  'the-entertainer', 'maple-leaf-rag', 'canon-in-d', 'minuet-in-g', 'prelude-in-c', 'ode-to-joy'];
const pieces = {};
for (const id of PICK) {
  const m = measured.find((x) => x.id === id);
  if (m) pieces[id] = m;
}

fs.writeFileSync(ROOT + '/js/comparison-data.js',
  '// AUTO-GENERATED by tools/gen-comparison-data.mjs — do not hand-edit.\n' +
  'window.DRD=window.DRD||{};DRD.COMPARE=' +
  JSON.stringify({ total: measured.length, fits, composerStats, eraStats, pieces }) + ';\n');

console.log('measured ' + measured.length + ' of ' + SONGS.length + ' pieces');
console.log('\nkeyboard tiers:');
for (const k of KEYS) console.log('  ' + String(k).padStart(2) + ' keys: ' + String(fits[k]).padStart(4) +
  '  (' + Math.round((fits[k] / measured.length) * 100) + '%)');
console.log('\ncomposers:');
for (const c of ['Frédéric Chopin', 'Franz Liszt', 'J. S. Bach', 'W. A. Mozart', 'Erik Satie',
  'Claude Debussy', 'Ludwig van Beethoven', 'Robert Schumann', 'Johannes Brahms']) {
  const s = composerStats[c];
  if (!s) { console.log('  ' + c + ' — none'); continue; }
  console.log('  ' + c.padEnd(22) + 'n=' + String(s.n).padStart(4) + ' median ' + String(s.median).padStart(3) +
    ' under30 ' + String(s.under30).padStart(3) + ' noSharps ' + String(s.noSharps).padStart(3) +
    ' easiest: ' + s.easiest.title.slice(0, 34) + ' (' + s.easiest.ds + ')');
}
console.log('\neras:');
for (const [g, s] of Object.entries(eraStats).sort((a, b) => b[1].n - a[1].n).slice(0, 8))
  console.log('  ' + g.padEnd(14) + 'n=' + String(s.n).padStart(4) + ' median ' + String(s.median).padStart(3) +
    ' under30 ' + String(s.under30).padStart(3) + ' medianSpan ' + String(s.medianSpan).padStart(2) + ' keys');
console.log('\nhead-to-head:');
for (const [id, m] of Object.entries(pieces))
  console.log('  ' + id.padEnd(18) + 'ds ' + String(m.ds).padStart(3) + ' span ' + String(m.span).padStart(2) +
    ' notes ' + String(m.notes).padStart(5) + ' nps ' + m.nps.toFixed(2) + ' sharps ' + m.sharps);
