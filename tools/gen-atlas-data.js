/* ============================================================================
   Data for the Atlas — one row per composer we hold sourced dates for.

   The map is a Gantt of lifespans: time across, composers packed into rows, each
   bar coloured by era and weighted by how much of that composer the library holds.
   Everything here is derived from data already in the repo — the catalogue plus
   the sourced lifespans — so the map cannot drift from the library.

   Run:  node tools/gen-atlas-data.js
   ========================================================================== */
const fs = require('fs');
const ROOT = require('path').dirname(__dirname);  // repo root, so this also works from a git worktree

global.window = {};
require(ROOT + '/js/data.js');
const SONGS = window.DRD.SONGS;

const datesSrc = fs.readFileSync(ROOT + '/js/composer-dates.js', 'utf8');
const DATES = JSON.parse(datesSrc.split('DRD.COMPOSER_DATES = ')[1].replace(/;\s*$/, ''));

// era for the colour band: the biography's own word where we have it, otherwise the
// dominant genre of that composer's pieces — never a guess of our own
function eraOf(name) {
  const d = DATES[name];
  if (d && d.era) {
    const e = d.era.toLowerCase();
    if (e.indexOf('renaissance') > -1) return 'Renaissance';
    if (e.indexOf('baroque') > -1) return 'Baroque';
    if (e.indexOf('classical') > -1) return 'Classical';
    if (e.indexOf('impressionist') > -1) return 'Impressionist';
    if (e.indexOf('ragtime') > -1) return 'Ragtime';
    if (e.indexOf('romantic') > -1) return 'Romantic';
  }
  // No biography names a period for this composer, and a genre is not an era —
  // "Sacred" says what they wrote, not when. So the band falls back to the century,
  // which is arithmetic on dates we can cite rather than a label we made up.
  return d ? d.century : 'Unknown';
}

const byComposer = {};
for (const s of SONGS) { if (s.composer) (byComposer[s.composer] = byComposer[s.composer] || []).push(s); }

const rows = [];
for (const [name, pieces] of Object.entries(byComposer)) {
  const d = DATES[name];
  if (!d) continue;                                   // no sourced dates → no bar; we do not invent one
  const sorted = pieces.slice().sort((a, b) => (a.ds == null ? 50 : a.ds) - (b.ds == null ? 50 : b.ds));
  const easiest = sorted[0];
  const known = pieces.filter((p) => (p.cover && p.cover.image) || p.featured)[0] || sorted[Math.floor(sorted.length / 2)];
  rows.push({
    n: name, b: d.b, d: d.d,
    era: eraOf(name),
    c: pieces.length,
    e: d.era || '',
    cy: d.century,
    ez: easiest ? [easiest.id, easiest.title, (easiest.ds == null ? 50 : easiest.ds)] : null,
    kn: known ? [known.id, known.title] : null
  });
}
rows.sort((a, b) => a.b - b.b || a.n.localeCompare(b.n));

const span = { from: Math.min.apply(null, rows.map((r) => r.b)), to: Math.max.apply(null, rows.map((r) => r.d)) };
fs.writeFileSync(ROOT + '/js/atlas-data.js',
  '/* Generated by tools/gen-atlas-data.js — do not hand-edit. */\n' +
  'window.DRD = window.DRD || {};\n' +
  'DRD.ATLAS = ' + JSON.stringify({ span: span, rows: rows }) + ';\n');

const eras = {};
rows.forEach((r) => { eras[r.era] = (eras[r.era] || 0) + 1; });
console.log('atlas: ' + rows.length + ' composers on the map, ' + span.from + '–' + span.to);
console.log('pieces represented: ' + rows.reduce((a, r) => a + r.c, 0) + ' / ' + SONGS.length);
console.log('eras: ' + JSON.stringify(eras));
console.log('size: ' + Math.round(fs.statSync(ROOT + '/js/atlas-data.js').size / 1024) + ' KB');
